"""Write one cw2 experiment per (method, task, seed) for the noisy-state comparison (paper Figures 4 and 9)
and the image-based comparison and ablations (Figures 3, 7 and 8).

The method settings are copied from the named experiments in noisy_state.yml / noisy_state_sac.yml, so
the sweep cannot drift from them. Experiment names are "<method>_<task>_s<seed>".
    python scripts/make_sweep_configs.py
    sbatch scripts/isambard/train.sbatch experiments/configs/kalmamba/noisy_state_sweep.yml kalmamba_walker-run_s0
"""
import os

import yaml

CONFIG_DIR = os.path.join(os.path.dirname(__file__), "..", "experiments", "configs", "kalmamba")
TASKS = ["cartpole-swingup", "quadruped-walk", "walker-walk", "walker-run"]  # Section 5
SEEDS = [0, 1, 2, 3]  # 4 seeds per task (Section 5)
SOURCES = {"noisy_state.yml": ["kalmamba", "kalmamba_mean", "kalmamba_noreg", "vrkn", "rssm"],
           "noisy_state_sac.yml": ["sac"],
           "image.yml": ["kalmamba", "kalmamba_mean", "no_mamba", "no_mcd", "no_reg", "vrkn", "rssm"]}


def main():
    for source, methods in SOURCES.items():
        docs = {d["name"]: d for d in yaml.safe_load_all(open(os.path.join(CONFIG_DIR, source)))}
        out = [{"name": "DEFAULT", "import_path": source}]
        for method in methods:
            params = docs[method].get("params", {})
            for task in TASKS:
                for seed in SEEDS:
                    p = yaml.safe_load(yaml.safe_dump(params))  # deep copy
                    p.setdefault("experiment", {})["seed"] = seed
                    p.setdefault("env", {})["env"] = task
                    out.append({"name": f"{method}_{task}_s{seed}", "params": p})
        target = os.path.join(CONFIG_DIR, source.replace(".yml", "_sweep.yml"))
        with open(target, "w") as f:
            f.write(f"# Generated by scripts/make_sweep_configs.py from {source}; do not edit.\n")
            yaml.safe_dump_all(out, f, sort_keys=False, explicit_start=True)
        print(f"wrote {len(out) - 1} experiments to {os.path.relpath(target)}")


if __name__ == "__main__":
    main()
